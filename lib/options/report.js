// Identify Your Options: Your Options Report.
//
// A private feedback report for the job seeker only. It never goes to an
// employer, and there is no way to share it with a recruiter from inside
// Comquat (decided 26 Nov 2026). The CV is a separate document.
//
// What goes in, by AI setting (signed-off split):
//   Off          the % match, and the gaps listed from the occupation data
//   Essentials   plus practical ways to close each gap
//   Full help    plus a step-by-step personal plan, and how to answer
//                interview questions about each gap
//
// Health details and the private "What helps me" notes never go to the AI.
// They only appear in the report if the person ticks to include them.

const { TRAITS } = require("./cards");
const { specMatch, tokens } = require("./match");
const ai = require("../anthropic");

const TRAIT = new Map(TRAITS.map((t) => [t.id, t]));
const RECRUITER =
  "Before you apply, talk to a specialist recruiter who works in this area, or ask them to interview you. " +
  "They can give you a full, honest view of how well you'd suit the role, and what employers in that field look for.";
const AI_NOTICE = "This content is generated by AI, and AI can make mistakes, so please check we haven't told a lie on any of your documents.";

function shortGap(s) {
  const t = String(s).replace(/\s+/g, " ").trim();
  return t.length > 160 ? t.slice(0, 157).replace(/\s+\S*$/, "") + "..." : t;
}

// Practical, rules-based ways to close a gap. No made-up courses or figures.
function ideasFor(occupation) {
  const ideas = [];
  const hasApp = (occupation.products || []).some((p) => /apprenticeship/i.test(p));
  if (hasApp) ideas.push(`Ask employers about an apprenticeship in ${occupation.title}${occupation.level ? ` (Level ${occupation.level})` : ""}. The training is built into the job, so you learn while you're paid.`);
  ideas.push("Learn on the job: tell employers you're ready to learn, and ask what training they give new starters.");
  ideas.push("Look for a short course or a Skills Bootcamp in these areas (search \"Skills Bootcamps\" on GOV.UK), or ask your local college what they run.");
  ideas.push("Volunteering or a short work placement can give you real examples to talk about.");
  return ideas;
}

// Strengths the person picked that relate to a gap, so they can show they could learn it.
function transferable(gap, traits) {
  const g = String(gap).toLowerCase();
  return traits.filter((pt) => { const tr = TRAIT.get(pt.id); return tr && tr.words.some((w) => g.includes(w)); }).map((pt) => TRAIT.get(pt.id).card).slice(0, 3);
}

async function coaching(occupation, gaps, traits) {
  const system =
    "You are a UK careers coach writing for a job seeker who may be returning to work, changing career, neurodivergent or living with a long-term illness. " +
    "Write in plain, warm UK English. Never use em-dashes. Never invent facts about the person: only use the strengths and examples given. " +
    "Never mention health conditions or diagnoses. Answer in JSON only.";
  const prompt = JSON.stringify({
    task: "For each gap, write a short honest answer the person could give if an interviewer asks about it, built on their own strengths and examples, plus one next step. Then write a short step-by-step plan (3 to 5 steps) for closing the gaps.",
    role: occupation.title,
    gaps: gaps.map(shortGap),
    strengths: traits.map((t) => ({ strength: (TRAIT.get(t.id) || {}).card, example: String(t.example || "").slice(0, 400) })),
    format: { answers: [{ gap: "string", answer: "string", nextStep: "string" }], plan: ["string"] },
  });
  const out = await ai.askJSON({ system, prompt, maxTokens: 3000 });
  return {
    answers: Array.isArray(out && out.answers) ? out.answers.slice(0, gaps.length) : [],
    plan: Array.isArray(out && out.plan) ? out.plan.slice(0, 6) : [],
  };
}

// profile: same shape as match.rank's, plus private: { howIWorkBest, helps: {traitId: text}, include: bool }
async function build(occupation, profile, level) {
  const m = specMatch(occupation, profile.personText || "");
  const traits = (profile.traits || []).filter((t) => TRAIT.has(t.id));
  const gapList = [...m.gaps, ...m.partial].slice(0, 8);
  const report = {
    role: { code: occupation.code, title: occupation.title, level: occupation.level, overview: occupation.overview, route: occupation.route },
    match: { percent: m.percent, strong: m.strong.length, partial: m.partial.length, gaps: m.gaps.length, total: m.total, how: m.how },
    strengths: m.strong.slice(0, 8).map(shortGap),
    gaps: gapList.map((g) => ({ gap: shortGap(g), transferable: transferable(g, traits) })),
    // Practical ways to close the gaps (Essentials and Full help), shown once under the gaps.
    ideas: level === "off" || !gapList.length ? [] : ideasFor(occupation),
    plan: [],
    coached: false,
    howYouWorkBest: null,
    nextStep: RECRUITER,
    aiNotice: null,
    sources: "Role details from Skills England occupational maps (Open Government Licence v3.0).",
  };
  const priv = profile.private || {};
  if (priv.include) {
    report.howYouWorkBest = {
      notes: String(priv.howIWorkBest || "").slice(0, 2000),
      helps: Object.entries(priv.helps || {}).map(([id, text]) => ({ strength: (TRAIT.get(id) || {}).card || "", helps: String(text).slice(0, 300) })).filter((h) => h.strength && h.helps),
    };
  }
  if (level === "full" && gapList.length && ai.hasKey()) {
    try {
      const c = await coaching(occupation, gapList, traits);
      c.answers.forEach((a, i) => { if (report.gaps[i]) { report.gaps[i].answer = String(a.answer || ""); report.gaps[i].nextStep = String(a.nextStep || ""); } });
      report.plan = c.plan.map(String);
      report.coached = true;
      report.aiNotice = AI_NOTICE;
    } catch (e) { report.coachingError = "The interview answers couldn't be written just now. Everything else in your report is here."; }
  }
  return report;
}

module.exports = { build, ideasFor, transferable, RECRUITER, AI_NOTICE, _tokens: tokens };
